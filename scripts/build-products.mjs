import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const projectRoot = process.cwd();
const catalogRoot = path.join(projectRoot, 'assets', 'products', 'catalog');
const imageExtensions = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif', '.gif']);

const isImage = name => imageExtensions.has(path.extname(name).toLowerCase());
const toWebPath = file => path.relative(projectRoot, file).split(path.sep).join('/');
const titleCase = value => value
  .replace(/[-_]+/g, ' ')
  .replace(/\b\w/g, letter => letter.toUpperCase());

async function imagesIn(folder) {
  try {
    const entries = await readdir(folder, { withFileTypes: true });
    return entries
      .filter(entry => entry.isFile() && isImage(entry.name))
      .map(entry => toWebPath(path.join(folder, entry.name)))
      .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
  } catch {
    return [];
  }
}

async function readDetails(productFolder, slug) {
  try {
    return JSON.parse(await readFile(path.join(productFolder, 'product.json'), 'utf8'));
  } catch (error) {
    if (error.code !== 'ENOENT') throw new Error(`${slug}/product.json is not valid JSON: ${error.message}`);
    return {};
  }
}

function resolveConfiguredPath(value, productFolder) {
  const candidate = path.resolve(productFolder, value);
  const relative = path.relative(projectRoot, candidate);
  if (relative.startsWith('..') || path.isAbsolute(relative)) {
    throw new Error(`Image path must stay inside the repository: ${value}`);
  }
  return candidate;
}

async function configuredVariants(config, productFolder) {
  const variants = {};
  for (const [name, value] of Object.entries(config)) {
    const values = Array.isArray(value) ? value : [value];
    const photos = [];
    for (const item of values) {
      const target = resolveConfiguredPath(item, productFolder);
      if (isImage(target)) photos.push(toWebPath(target));
      else photos.push(...await imagesIn(target));
    }
    if (photos.length) variants[name] = [...new Set(photos)];
  }
  return variants;
}

async function discoveredVariants(productFolder) {
  const variants = {};
  const directPhotos = await imagesIn(productFolder);
  if (directPhotos.length) variants.Default = directPhotos;

  const entries = await readdir(productFolder, { withFileTypes: true });
  for (const entry of entries) {
    if (!entry.isDirectory() || entry.name.startsWith('_')) continue;
    const photos = await imagesIn(path.join(productFolder, entry.name));
    if (photos.length) variants[titleCase(entry.name)] = photos;
  }
  return variants;
}

const folderEntries = await readdir(catalogRoot, { withFileTypes: true });
const products = [];

for (const entry of folderEntries) {
  if (!entry.isDirectory() || entry.name.startsWith('_')) continue;
  const slug = entry.name;
  const productFolder = path.join(catalogRoot, slug);
  const details = await readDetails(productFolder, slug);
  if (details.hidden === true) continue;

  const variants = details.variants
    ? await configuredVariants(details.variants, productFolder)
    : await discoveredVariants(productFolder);

  if (!Object.keys(variants).length) {
    console.warn(`Skipping ${slug}: no product images found.`);
    continue;
  }

  products.push({
    id: details.id || slug,
    name: details.title || titleCase(slug),
    brand: details.brand || 'Sharif Store',
    price: Number(details.price) || 0,
    new_drop: details.newDrop !== false,
    sizes: Array.isArray(details.sizes) && details.sizes.length ? details.sizes.map(String) : ['37', '38', '39', '40', '41'],
    description: details.description || '',
    variants,
    order: Number(details.order) || 999
  });
}

products.sort((a, b) => a.order - b.order || a.name.localeCompare(b.name));
for (const product of products) delete product.order;

const output = `/* Generated by scripts/build-products.mjs. Do not edit by hand. */\nwindow.PRODUCTS_DATA=${JSON.stringify(products, null, 2)};\n`;
await writeFile(path.join(projectRoot, 'products-data.js'), output);
console.log(`Built ${products.length} product${products.length === 1 ? '' : 's'} into products-data.js.`);
